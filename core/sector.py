# 评分权重的**验证状态**（单一事实来源：UI / 系统提示词 / 工具输出统一引用这里）
#
# 为什么必须有这段：`FACTOR_WEIGHTS` 的数值来源是「删掉北向资金后按原主观比例
# 机械缩放（÷0.85）」，**从未做过 IC 验证**。若不显式声明，AI 助手会把
# 「综合评分 82」当成经证实的结论讲给用户 —— 那是把未验证的假设包装成数据结论。
#
# 实测（2026-10-07）：
#   ① 单区间（50 只池 / 2024-01~2025-06 / 64 期 / horizon 20）：
#      20日动量 IC −0.1292 (t −5.19)、均线多头排列 −0.0744 (t −3.60)、
#      站上20日均线 −0.0920 (t −3.82)、年化波动率 −0.0913 (t −2.48)。
#   ② **样本外稳健性**（30 只池 / 2023 & 2024 & 2025 三年 × 10/20/60 日持有期 = 9 配置）：
#      20日动量   **9/9 全为负号**，8/9 显著 → 方向相反**稳健**，不是单区间偶然；
#      年化波动率  9/9 同向（低波动更好），6/9 显著 → 与权重假设一致；
#      均线多头排列 8/9 为负但**仅 2/9 显著** → 方向偏负、**区分度本身就弱**；
#      站上20日均线 9/9 为负但仅 1/9 显著 → 同上。
#   ⇒ 单区间里"显著方向相反"的均线类因子，在样本外**没站住显著性** ——
#      这是"多区间检验"存在的意义，也是不能只拿一段样本下结论的活例证。
#   ③ 四个因子分层收益全部不单调；趋势与均线排列相关 0.47~0.57（重复计分）。
#   详见 `output/因子有效性分析报告.md`。
#
# ⚠️ 措辞边界：要写「未验证」与「方向存疑」，**不要**写「无效」——
#    样本限于 2023~2025（A 股反转/震荡市为主）与当期成分池，
#    只支持"当前权重在这些样本上没有依据"，不支持"这些因子永远无效"。
#    尤其**动量在趋势性牛市里可能转正**，本结论不覆盖那种市场形态。
