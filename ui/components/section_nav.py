# -*- coding: utf-8 -*-
"""页面区块快速定位（**左侧栏导航**）—— 长页面的通用组件。

背景：
  · 2026-10-15 用户提议："一个页面里含多块内容（热点新闻 = 新闻 + 排行榜 + 知乎）应能快速定位"；
  · 同日用户修正：**"下拉应放左侧主板块下，点开某一主板块即可看到它下面的副模块"**
    ⇒ 从"页面顶部的下拉框"改为"**左侧栏的折叠分组**"：
        · **主板块** = 侧栏里的分组标题（= 当前页面），点它展开/收起；
        · **副模块** = 展开后列出的单选项，选中即只渲染那一块。
    ⚠️ 不采用 Streamlit 原生多页导航的原因：它只能扁平列页面，**不支持"页内副模块"嵌套**；
       而 `st.sidebar.expander` + `st.radio` 正好给出"主板块 → 副模块"的层级感。

设计取舍（每一条都为规避本项目已踩过的坑）：
1. **默认「全部显示」** ⇒ 与改造前行为**逐字节一致**，既有冒烟断言零破坏；
   用户主动选某个区块时才只渲染那一块（顺带省掉其他区块的取数/联网开销）。
2. **`section_nav` 只负责选择**，渲染仍由调用方 `if visible(...)` 决定 ——
   不搞魔法回调，读代码时"哪个区块在什么条件下渲染"一目了然。
3. ⚠️ **全局口径/免责必须放在主区域、导航之外**（`above=` 或直接写在其前）：
   任何选择下都要可见。
4. ⚠️ **区块自身的"使用边界"声明留在区块内**（选中它才显示）——
   与 3 不冲突：全局的常驻，局部的随块走。旧事故是"声明被跳过而消失"，
   这里"没看这块就不显示这块的声明"是合理的（但**不得**把全局声明也塞进块里）。
5. ⚠️ **切换区块会触发整页 rerun** ⇒ 慢的根因不在本组件，而在"被选中区块的取数"。
   调用方必须用 `st.cache_data` 缓存昂贵加载（行业评估 / 个股推荐 / 热榜 / 鉴权探测），
   否则每次切换都重新联网。本组件只保证"**未选中的区块一律不执行**"。
"""
from __future__ import annotations

import streamlit as st

# 「全部显示」哨兵值：默认项，保持改造前行为
ALL = "🔎 全部显示"


def section_nav(options, *, key: str, group_label: str = "本页板块导航",
                above=None) -> str:
    """在**左侧栏**渲染"主板块（折叠分组）→ 副模块（单选）"，返回当前选择。

    Args:
        options: 副模块名（顺序 = 页面里的呈现顺序）。
        key: 单选控件的 key（同一页面多组必须不同）。
        group_label: 左侧栏**主板块**的标题（通常是当前页面名，如 "📰 热点新闻"）。
        above: 可选回调，在**主区域、导航之外**渲染内容（全局口径/免责），
               任何选择下都可见 —— 别把它塞进侧栏（侧栏收起时会看不到）。
    Returns:
        选中的副模块名，或 `ALL`（全部显示）。
    """
    if above is not None:
        above()
    opts = tuple(options)
    if len(opts) <= 1:
        return ALL                                  # 只有一个区块不需要选择器
    # ⚠️ 用 `st.sidebar.expander` 而非 `with st.sidebar:` —— 后者在侧栏被折叠/未渲染时
    #    某些 Streamlit 版本会退化到主区域，导致"导航跑到正文里"。
    with st.sidebar.expander(group_label, expanded=True):
        return st.radio(
            "副模块", (ALL,) + opts, index=0, key=key, label_visibility="collapsed",
            help="选择后**只显示该副模块**，便于在长页面里快速定位；默认全部显示。")


def visible(selection: str, name: str) -> bool:
    """当前是否应渲染名为 `name` 的区块。"""
    return selection == ALL or selection == name
